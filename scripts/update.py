#!/usr/bin/env python3
"""Pin the formula to the current, checksum-verified public CLI release."""

import hashlib
import json
from pathlib import Path
import re
import urllib.request

ORIGIN = "https://www.cool.computer"
FORMULA = Path(__file__).resolve().parents[1] / "Formula" / "cool.rb"


def fetch(path):
    with urllib.request.urlopen(ORIGIN + path, timeout=60) as response:
        return response.read()


def update():
    pointer = json.loads(fetch("/cli/installers/current.json"))
    version = pointer["version"]
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ValueError("Invalid release version")
    release_path = f"/cli/releases/{version}/"
    manifest = json.loads(fetch(release_path + "release-manifest.json"))
    if (manifest["schemaVersion"], manifest["product"], manifest["command"], manifest["version"]) != (
        3, "coolcomputer", "cool", version
    ):
        raise ValueError("Unexpected release manifest")
    if FORMULA.exists():
        installed = re.search(r'^  version "(\d+\.\d+\.\d+)"$', FORMULA.read_text(), re.M)
        if installed is None:
            raise ValueError("Existing formula has no release version")
        if tuple(map(int, version.split("."))) < tuple(map(int, installed[1].split("."))):
            raise ValueError("Refusing to downgrade the formula")

    archives = {}
    for platform in ("darwin-arm64", "darwin-x64", "linux-arm64", "linux-x64"):
        artifacts = [entry for entry in manifest["artifacts"] if entry["platform"] == platform]
        if len(artifacts) != 1:
            raise ValueError(f"Expected exactly one artifact for {platform}")
        artifact = artifacts[0]
        extension = "zip" if platform.startswith("darwin") else "tar.gz"
        filename = f"coolcomputer-{version}-{platform}.{extension}"
        archive = artifact["archive"]
        if artifact["executable"] != "cool" or archive["file"] != filename:
            raise ValueError(f"Unexpected artifact for {platform}")
        digest = archive["sha256"]
        if not re.fullmatch(r"[0-9a-f]{64}", digest):
            raise ValueError(f"Invalid archive checksum for {platform}")
        if hashlib.sha256(fetch(release_path + filename)).hexdigest() != digest:
            raise ValueError(f"Archive checksum mismatch for {platform}")
        archives[platform] = (ORIGIN + release_path + filename, digest)

    lines = [
        "# Generated by scripts/update.py from the official release manifest.",
        "class Cool < Formula",
        '  desc "Create, publish, and manage Cool Computers from your terminal"',
        f'  homepage "{ORIGIN}"',
        f'  version "{version}"',
        "  license :cannot_represent",
    ]
    for system, platform in (("macos", "darwin"), ("linux", "linux")):
        lines.extend(["", f"  on_{system} do"])
        for architecture, target in (("arm", "arm64"), ("intel", "x64")):
            url, digest = archives[f"{platform}-{target}"]
            lines.extend([
                f"    on_{architecture} do",
                f'      url "{url}"',
                f'      sha256 "{digest}"',
                "    end",
            ])
        lines.append("  end")
    lines.extend([
        "",
        "  def install",
        '    bin.install "cool"',
        '    generate_completions_from_executable(bin/"cool", "completion")',
        "  end",
        "",
        "  def caveats",
        "    <<~EOS",
        "      Run cool agents install to add Cool Computers instructions to your local coding agents.",
        "      Upgrade with brew upgrade the-money-company-limited/tap/cool.",
        "    EOS",
        "  end",
        "",
        "  test do",
        '    assert_match version.to_s, shell_output("#{bin}/cool --version")',
        '    assert_match "publish", shell_output("#{bin}/cool --help")',
        "  end",
        "end",
        "",
    ])
    FORMULA.write_text("\n".join(lines))
    print(f"Verified all four archives for Cool Computers {version}")


if __name__ == "__main__":
    update()
